    # 左側標籤
    ax.text(x_lbl0, yc + box_h*0.55, f"{code}　{name}", ha="left", va="center",
            fontsize=12.5, fontweight="bold", color="#1F3864")
    ax.text(x_lbl0, yc - box_h*0.55, rooms, ha="left", va="center",
            fontsize=8.0, color="#666", wrap=True)
    # 步驟盒
    m = len(steps)
    pitch = (x_s1 - x_s0) / m
    bw = pitch * 0.82
    for i, (label, trade) in enumerate(steps):
        x = x_s0 + i * pitch
        color = TRADE[trade][0]
        box = FancyBboxPatch((x, yc - box_h/2), bw, box_h,
                             boxstyle="round,pad=0.002,rounding_size=0.004",
                             linewidth=0.7, edgecolor="white", facecolor=color, zorder=3)
        ax.add_patch(box)
        # 文字顏色：亮底用深字
        light = trade in ("人造石", "燈具", "鷹架")
        tc = "#222222" if light else "white"
        ax.text(x + bw/2, yc, f"{circ(i+1)}\n{wrap(label)}", ha="center", va="center",
                fontsize=7.4, color=tc, zorder=4, linespacing=1.05)
        # 箭頭
        if i < m - 1:
            ax.annotate("", xy=(x + pitch, yc), xytext=(x + bw, yc),
                        arrowprops=dict(arrowstyle="-|>", color="#777", lw=1.0), zorder=2)

