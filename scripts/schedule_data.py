def shift(s: str) -> dt.datetime:
    return _d(s) + dt.timedelta(days=SHIFT_DAYS)

def workdays(start: dt.datetime, end: dt.datetime) -> int:
    """含頭含尾、扣除週日的工作天數（週 6 工作天）。"""
    days = 0
    cur = start
    while cur <= end:
        if cur.weekday() != 6:  # 6 = Sunday
            days += 1
        cur += dt.timedelta(days=1)
    return days

