def zones():
    """回傳： (樓層, 區域, 類型, 進場dt, 退場dt, 在場週, [(工種, start_dt)...排序], 順位)"""
    parsed = []
    for floor, name, typ, segs, ex in _ZONES:
        ps = sorted(((t, _d(s)) for t, s in segs), key=lambda x: x[1])
        enter = ps[0][1]
        exit_ = _d(ex)
        weeks = round((exit_ - enter).days / 7)
        parsed.append([floor, name, typ, enter, exit_, weeks, ps])
    parsed.sort(key=lambda z: (z[3], z[0]))   # 依進場日排順位
    for i, z in enumerate(parsed, start=1):
        z.append(i)
    return parsed

